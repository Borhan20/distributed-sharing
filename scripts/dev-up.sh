#!/usr/bin/env bash
# Try pool on this computer with one command (development only).
#
# Starts the server in DEV MODE (sign in with any name, no password) with the
# object store, builds the agent, connects this computer to your dev account,
# shares it with a group and starts it. Safe to run again: existing settings,
# data, enrollment and sharing limits are kept.
#
#   scripts/dev-up.sh [--user NAME] [--group NAME] [--no-share]
#   scripts/dev-down.sh            # stop it again (keeps all data)
#
# Never use dev mode on a shared server: anyone could sign in as anyone.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
API="http://127.0.0.1:8000"
COMPOSE=(docker compose -f "$ROOT/deploy/compose.yaml" --profile storage)
AGENT="$ROOT/agent/bin/pool-agent"
DEV_USER="${POOL_DEV_USER:-${USER:-dev}}"
GROUP="${POOL_DEV_GROUP:-my-lab}"
SHARE=1

usage() { sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; }
while [ $# -gt 0 ]; do
  case "$1" in
    --user) DEV_USER="$2"; shift 2 ;;
    --group) GROUP="$2"; shift 2 ;;
    --no-share) SHARE=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "$1 is missing. $2"; }
json() { python3 -c "import json,sys; d=json.load(sys.stdin); print($1)"; }

[[ "$DEV_USER" =~ ^[A-Za-z0-9._-]{1,64}$ ]] || fail "--user must be letters, digits, dot, dash or underscore"
[[ "$GROUP" =~ ^[a-z0-9][a-z0-9-]{1,62}$ ]] || fail "--group must be lowercase letters, digits and dashes (e.g. my-lab)"

step "Checking what this computer has"
need docker "Install Docker: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is missing (the 'docker compose' command)."
docker info >/dev/null 2>&1 || fail "Docker is installed but not running, or your user may not use it."
need curl "Install curl with your package manager."
need python3 "Install Python 3 with your package manager."
if [ "$SHARE" = 1 ]; then need go "Install Go 1.23 or newer (https://go.dev/dl/) to build the agent, or use --no-share."; fi

step "Settings (deploy/.env, kept if they already exist)"
python3 - "$ROOT/deploy" "$DEV_USER" <<'PY'
import json, os, secrets, sys
deploy, user = sys.argv[1], sys.argv[2]
env_path, s3_path = os.path.join(deploy, ".env"), os.path.join(deploy, "seaweedfs-s3.json")

def write_private(path, text):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)

if not os.path.exists(env_path):
    write_private(env_path, "\n".join([
        "# Generated by scripts/dev-up.sh for local development. Never commit this file.",
        f"POSTGRES_PASSWORD={secrets.token_hex(16)}",
        f'POOL_SERVER_ADMINS=["{user}"]',
        "POOL_BIND=127.0.0.1",
        f"KEYCLOAK_ADMIN_PASSWORD={secrets.token_hex(16)}",
        "", ""]))
    print("created deploy/.env with new random passwords")
env = open(env_path).read()
configured = {line.split("=", 1)[0] for line in env.splitlines() if "=" in line and line.split("=", 1)[1].strip()}
if "POOL_S3_ACCESS_KEY" in configured:
    print("object store: already configured, kept")
elif os.path.exists(s3_path):
    print("object store: deploy/seaweedfs-s3.json exists but deploy/.env has no keys; left as is")
else:
    access, secret = secrets.token_hex(16), secrets.token_hex(32)
    lines = [l for l in env.splitlines() if not l.startswith("POOL_S3_")]
    lines += ["# Object store on this computer (scripts/dev-up.sh)",
              "POOL_S3_ENDPOINT=http://seaweedfs:8333",
              "POOL_S3_PUBLIC_ENDPOINT=http://127.0.0.1:8333",
              f"POOL_S3_ACCESS_KEY={access}", f"POOL_S3_SECRET_KEY={secret}", ""]
    write_private(env_path, "\n".join(lines))
    cfg = json.load(open(os.path.join(deploy, "seaweedfs-s3.json.example")))
    cfg["identities"][0]["credentials"] = [{"accessKey": access, "secretKey": secret}]
    write_private(s3_path, json.dumps(cfg, indent=2) + "\n")
    print("object store: created keys in deploy/.env and deploy/seaweedfs-s3.json")
PY

step "Starting the server (first run builds images; this can take a few minutes)"
"${COMPOSE[@]}" up -d --build --wait
for _ in $(seq 1 60); do curl -fsS "$API/readyz" >/dev/null 2>&1 && break; sleep 1; done
curl -fsS "$API/readyz" >/dev/null || fail "the server did not become ready; see: ${COMPOSE[*]} logs api"
echo "server: $(curl -fsS "$API/readyz")"

code=$(curl -s -o /dev/null -w '%{http_code}' -X POST "$API/dev/token" -H 'content-type: application/json' \
  -d "{\"username\": \"$DEV_USER\"}")
[ "$code" = 200 ] || fail "the server is not in dev mode (POST /dev/token returned $code). Remove POOL_DEV_MODE=false from deploy/.env, or use the normal setup."
TOKEN=$(curl -fsS -X POST "$API/dev/token" -H 'content-type: application/json' -d "{\"username\": \"$DEV_USER\"}" | json 'd["access_token"]')
api() { curl -fsS -H "Authorization: Bearer $TOKEN" -H 'content-type: application/json' "$@"; }

if [ "$SHARE" = 0 ]; then
  printf '\nDone. Open %s and sign in as "%s" (dev mode: no password).\n' "$API" "$DEV_USER"
  exit 0
fi

step "Group \"$GROUP\" for $DEV_USER"
status=$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $TOKEN" "$API/api/v1/groups/$GROUP")
if [ "$status" = 200 ]; then
  echo "you are already in $GROUP"
else
  status=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H "Authorization: Bearer $TOKEN" -H 'content-type: application/json' \
    -d "{\"name\": \"$GROUP\", \"display_name\": \"$GROUP\", \"template\": \"research-team\"}" "$API/api/v1/groups")
  [ "$status" = 201 ] || fail "could not create group $GROUP (HTTP $status). It may belong to someone else: use --group another-name."
  echo "created $GROUP; you are its coordinator"
fi

step "Building the agent"
(cd "$ROOT/agent" && CGO_ENABLED=0 go build -o bin/pool-agent ./cmd/pool-agent)  # static: apps need it
"$AGENT" version

step "Connecting this computer"
AGENT_STATUS=$("$AGENT" status)
AGENT_HOME=$(printf '%s\n' "$AGENT_STATUS" | sed -n 's/^Home: //p')
profile_line=$(printf '%s\n' "$AGENT_STATUS" | grep '^Profile default ' || true)
if [ -z "$profile_line" ]; then
  enroll_code=$(api -X POST "$API/api/v1/devices/enrollment-codes" | json 'd["code"]')
  "$AGENT" enroll --server "$API" --code "$enroll_code" --name "$(hostname -s 2>/dev/null || hostname)" --insecure-http
  AGENT_STATUS=$("$AGENT" status)
  profile_line=$(printf '%s\n' "$AGENT_STATUS" | grep '^Profile default ')
else
  echo "already connected"
fi
enrolled_server=$(printf '%s\n' "$profile_line" | awk '{for (i = 1; i < NF; i++) if ($i == "server") print $(i + 1)}')
DEVICE_ID=$(printf '%s\n' "$profile_line" | awk '{for (i = 1; i < NF; i++) if ($i == "device") print $(i + 1)}')
[ "$enrolled_server" = "$API" ] || fail "this computer's agent is connected to $enrolled_server, not $API. Use another POOL_AGENT_HOME to try the local server."
if ! api "$API/api/v1/devices" | DEVICE_ID="$DEVICE_ID" python3 -c 'import json,os,sys; sys.exit(0 if any(d["id"] == os.environ["DEVICE_ID"] for d in json.load(sys.stdin)) else 1)'; then
  fail "this computer is connected under a different user. Run again with --user set to that user's name."
fi

step "Sharing this computer with $GROUP"
"$AGENT" share "$GROUP"

step "Starting the agent in the background"
mkdir -p "$AGENT_HOME"
LOG="$AGENT_HOME/agent.log"
# Stop an agent started from this checkout (it may be an older build); never touch other programs.
if pgrep -f "^$AGENT run" >/dev/null 2>&1; then
  pkill -TERM -f "^$AGENT run" || true
  for _ in $(seq 1 20); do pgrep -f "^$AGENT run" >/dev/null 2>&1 || break; sleep 0.5; done
  echo "stopped the previous agent"
fi
if command -v setsid >/dev/null 2>&1; then
  setsid nohup "$AGENT" run >>"$LOG" 2>&1 </dev/null &
else
  nohup "$AGENT" run >>"$LOG" 2>&1 </dev/null &
fi
echo $! >"$AGENT_HOME/agent.pid"
disown 2>/dev/null || true

printf 'waiting for the server to list this computer in %s ' "$GROUP"
ok=0
for _ in $(seq 1 45); do
  if api "$API/api/v1/devices/$DEVICE_ID" | GROUP="$GROUP" python3 -c 'import json,os,sys; d=json.load(sys.stdin); sys.exit(0 if d["online"] and os.environ["GROUP"] in d["shared_with"] else 1)'; then
    ok=1; break
  fi
  printf '.'; sleep 1
done
echo
[ "$ok" = 1 ] || fail "the agent did not come online in time; see $LOG"

cat <<EOF

Ready.
  Open:      $API   (sign in as "$DEV_USER"; dev mode has no password)
  Group:     $GROUP, with this computer shared (limits shown above; change with: $AGENT share $GROUP --cpu-percent 75)
  Try it:    open the group, tab Jobs, "Submit a job": the example job runs as-is
  Guide:     $API/guide
  Logs:      agent $LOG ; server: ${COMPOSE[*]} logs -f api
  Stop work: $AGENT kill      Stop all: scripts/dev-down.sh
EOF
